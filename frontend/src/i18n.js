// safe localStorage access (jsdom in tests may not provide it)
const _hasWindow = typeof window !== 'undefined' && window !== null
const _hasLocalStorage = _hasWindow && typeof window.localStorage !== 'undefined'

let _locale = 'en'
try{
  if(_hasLocalStorage){
    const v = window.localStorage.getItem('locale')
    if(v) _locale = v
  }
}catch(e){ /* ignore storage errors in test env */ }

function isRtl(l){ return l==='fa' || l==='ar' }

function applyDir(){ if(typeof document !== 'undefined'){
  try{
    document.documentElement.lang = _locale
    document.documentElement.dir = isRtl(_locale) ? 'rtl' : 'ltr'
  }catch(e){ /* ignore in test env */ }
}}
applyDir()

export function t(key){ return (translations[_locale] && translations[_locale][key]) || (translations['en'] && translations['en'][key]) || key }
export function tf(key, vars){
  let s = t(key)
  if(!vars) return s
  Object.entries(vars).forEach(([k,v])=>{ s = s.split(`{${k}}`).join(String(v)) })
  return s
}
export function getLocale(){ return _locale }
export function setLocale(l){ _locale = l; try{ if(_hasLocalStorage) window.localStorage.setItem('locale', l) }catch(e){}; applyDir(); try{ window.dispatchEvent(new CustomEvent('app:lang-changed', { detail: { locale: l } })) }catch(e){} }
export function isLocaleRtl(l){ return isRtl(l) }

export default { t, tf, getLocale, setLocale, isLocaleRtl }
